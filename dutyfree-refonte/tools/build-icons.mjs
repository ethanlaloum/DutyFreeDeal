// Generates js/icons.js from @phosphor-icons/core (MIT). Run: node tools/build-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const assets = join(root, 'node_modules/@phosphor-icons/core/assets');

const regular = [
  'magnifying-glass', 'shopping-bag', 'heart', 'map-pin', 'squares-four', 'caret-down', 'caret-right',
  'caret-left', 'caret-up', 'x', 'arrow-right', 'arrow-left', 'arrow-up-right', 'check', 'plus', 'minus',
  'truck', 'seal-check', 'storefront', 'package', 'tag', 'binoculars', 'trash', 'clock', 'info', 'warning',
  'car', 'house-line', 'receipt', 'funnel', 'envelope-simple', 'globe-simple', 'arrow-counter-clockwise'
];
const fill = ['heart', 'check-circle'];

const inner = svg => svg.replace(/^.*?<svg[^>]*>/s, '').replace(/<\/svg>\s*$/s, '').trim();
const icons = {};
for (const name of regular) icons[name] = inner(readFileSync(join(assets, 'regular', `${name}.svg`), 'utf8'));
for (const name of fill) icons[`${name}-fill`] = inner(readFileSync(join(assets, 'fill', `${name}-fill.svg`), 'utf8'));

const body = `/* Generated by tools/build-icons.mjs from @phosphor-icons/core (MIT License, phosphoricons.com). Do not edit by hand. */
export const ICONS = ${JSON.stringify(icons, null, 0).replace(/","/g, '",\n  "')};
`;
writeFileSync(join(root, 'js/icons.js'), body);
console.log(`js/icons.js: ${Object.keys(icons).length} icons`);
